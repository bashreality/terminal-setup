#!/usr/bin/env bash
# ==============================================================================
# sync.sh — zapisuje aktualny stan terminala z TEGO Maca do repo.
#
#   ./sync.sh            skopiuj configi, odśwież Brewfile, plugins.lock i profil iTerm2
#   git diff             sprawdź zmiany
#   git commit -am "update" && git push
#
# Pomija .zshenv: wersja w repo jest celowo odporna na brak ~/.cargo/env.
# ==============================================================================

set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOME_SRC="$REPO_DIR/home"

copy_in() {
  local rel="$1"
  local src="$HOME/$rel" dst="$HOME_SRC/$rel"
  [[ -f $src ]] || { echo "  brak:   ~/$rel"; return 0; }
  # Na Macu zainstalowanym przez install.sh pliki są symlinkami do repo.
  [[ $src -ef $dst ]] && return 0
  mkdir -p "$(dirname "$dst")"
  if ! cmp -s "$src" "$dst"; then
    cp -p "$src" "$dst"
    echo "  zmiana: ~/$rel"
  fi
}

echo "==> Configi"
while IFS= read -r -d '' file; do
  rel="${file#"$HOME_SRC"/}"
  [[ $rel == .zshenv ]] && continue
  copy_in "$rel"
done < <(find "$HOME_SRC" -type f ! -name .DS_Store -print0)

# Nowe moduły zsh pojawiają się automatycznie (local.zsh zostaje prywatny).
for file in "$HOME"/.config/zsh/*.zsh "$HOME"/.config/zsh/tests/*.zsh; do
  [[ -f $file ]] || continue
  rel="${file#"$HOME"/}"
  [[ $rel == .config/zsh/local.zsh ]] && continue
  copy_in "$rel"
done

echo "==> Brewfile"
brew bundle dump --file="$REPO_DIR/Brewfile" --force

echo "==> plugins.lock"
{
  echo "# <path relative to \$HOME> <git url> <commit>"
  echo "# Regenerated by sync.sh. install.sh checks out exactly these commits."
  while read -r rel _ _; do
    [[ -z ${rel:-} || $rel == \#* ]] && continue
    dir="$HOME/$rel"
    if [[ -d $dir/.git ]]; then
      url="$(git -C "$dir" remote get-url origin | sed -E 's#https://git::@#https://#; s#\.git$##')"
      echo "$rel $url $(git -C "$dir" rev-parse HEAD)"
    else
      grep -F "$rel " "$REPO_DIR/plugins.lock"
    fi
  done < "$REPO_DIR/plugins.lock"
} > "$REPO_DIR/plugins.lock.tmp"
mv "$REPO_DIR/plugins.lock.tmp" "$REPO_DIR/plugins.lock"

echo "==> iTerm2"
if defaults read com.googlecode.iterm2 "New Bookmarks" >/dev/null 2>&1; then
  tmp="$(mktemp -d)"
  defaults export com.googlecode.iterm2 "$tmp/iterm.plist"
  plutil -extract "New Bookmarks" json -o "$tmp/profiles.json" "$tmp/iterm.plist"
  default_guid="$(defaults read com.googlecode.iterm2 "Default Bookmark Guid")"
  python3 - "$tmp/profiles.json" "$REPO_DIR/extras/iterm2/profile.json" "$default_guid" <<'EOF'
import json, sys
profiles = json.load(open(sys.argv[1]))
profile = next((p for p in profiles if p.get("Guid") == sys.argv[3]), profiles[0])
profile["Name"] = "bashreality"
profile.pop("Working Directory", None)
profile.pop("Default Bookmark", None)
json.dump({"Profiles": [profile]}, open(sys.argv[2], "w"), indent=2, sort_keys=True)
EOF
  rm -rf "$tmp"
fi

echo
git -C "$REPO_DIR" status --short
